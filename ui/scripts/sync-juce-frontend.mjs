#!/usr/bin/env node
/**
 * Copies JUCE's official JavaScript frontend library into ui/src/juce/.
 *
 * JUCE does NOT publish this on npm (there is no `juce-framework-frontend`
 * package). It lives in the framework checkout at
 *   modules/juce_gui_extra/native/javascript/
 * and MUST come from the same JUCE version the plugin links against, because
 * the relay wire protocol is versioned with the framework.
 *
 * If no JUCE checkout is found (fresh clone, UI-only work), a dev-mode
 * fallback is written instead so `npm run dev` and `tsc` still work in a plain
 * browser. The fallback has no native backend and is never what ships.
 */
import { existsSync, mkdirSync, readdirSync, copyFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const uiRoot = resolve(here, '..');
const repoRoot = resolve(uiRoot, '..');
const target = join(uiRoot, 'src', 'juce');

const RELATIVE_JS_PATH = join('modules', 'juce_gui_extra', 'native', 'javascript');

/** Places FetchContent and common manual setups leave JUCE. */
function candidateJuceRoots() {
  const fromEnv = process.env.JUCE_DIR ? [process.env.JUCE_DIR] : [];
  const buildDirs = ['build', 'build-debug', 'build-release', 'cmake-build-debug', 'cmake-build-release'];

  return [
    ...fromEnv,
    ...buildDirs.map((b) => join(repoRoot, b, '_deps', 'juce-src')),
    join(repoRoot, 'JUCE'),
    join(repoRoot, '..', 'JUCE'),
  ];
}

function findJuceJavascriptDir() {
  for (const root of candidateJuceRoots()) {
    const dir = join(root, RELATIVE_JS_PATH);
    if (existsSync(dir) && statSync(dir).isDirectory()) return dir;
  }
  return null;
}

function copyDirShallow(from, to) {
  mkdirSync(to, { recursive: true });
  let count = 0;
  for (const entry of readdirSync(from, { withFileTypes: true })) {
    const src = join(from, entry.name);
    const dst = join(to, entry.name);
    if (entry.isDirectory()) {
      count += copyDirShallow(src, dst);
    } else if (/\.(js|mjs|ts|d\.ts|json)$/.test(entry.name)) {
      copyFileSync(src, dst);
      count += 1;
    }
  }
  return count;
}

/*
 * The fallback below implements EXACTLY the module surface JUCE's index.js
 * exports — no more:
 *   getSliderState, getToggleState, getComboBoxState, getNativeFunction,
 *   getBackendResourceAddress, ControlParameterIndexUpdater
 *
 * Everything else (initialisationData, the backend event bus) lives on the
 * injected `window.__JUCE__` global, not on the module. See
 * src/types/juce-globals.d.ts.
 */
const FALLBACK = `/* GNARL dev-mode fallback for JUCE's frontend library.
 *
 * AUTO-GENERATED by scripts/sync-juce-frontend.mjs — do not edit.
 * Replaced by the real JUCE implementation as soon as a JUCE checkout exists
 * (configure the CMake build once, then run \\\`npm run sync-juce\\\`).
 *
 * Purpose: let the UI run in a plain browser with no plugin behind it, so
 * components can be built and type-checked. Every control is backed by
 * in-memory state and nothing reaches an audio engine.
 *
 * This mirrors the module surface only. Note that JUCE's real
 * check_native_interop.js ALSO installs a browser fallback for
 * window.__JUCE__, so once synced, browser dev works without this file.
 */

class ListenerList {
  constructor() {
    this.listeners = new Map();
    this.listenerId = 0;
  }
  addListener(fn) {
    const id = this.listenerId++;
    this.listeners.set(id, fn);
    return id;
  }
  removeListener(id) {
    this.listeners.delete(id);
  }
  callListeners(payload) {
    for (const [, fn] of this.listeners) fn(payload);
  }
}

if (typeof window.__JUCE__ === "undefined") {
  window.__JUCE__ = {
    postMessage() {},
    initialisationData: {
      __juce__platform: [],
      __juce__functions: [],
      __juce__registeredGlobalEventIds: [],
      __juce__sliders: [],
      __juce__toggles: [],
      __juce__comboBoxes: [],
    },
    backend: {
      addEventListener: () => [null, 0],
      removeEventListener: () => {},
      emitEvent: () => {},
    },
  };
}

class MockSliderState {
  constructor(name) {
    this.name = name;
    this.identifier = "__juce__slider" + name;
    this.scaledValue = 0;
    this.properties = {
      start: 0, end: 1, skew: 1,
      name, label: "", numSteps: 100, interval: 0, parameterIndex: -1,
    };
    this.valueChangedEvent = new ListenerList();
    this.propertiesChangedEvent = new ListenerList();
  }
  setNormalisedValue(v) {
    const clamped = Math.min(1, Math.max(0, v));
    const { start, end, skew } = this.properties;
    this.scaledValue = Math.pow(clamped, 1 / skew) * (end - start) + start;
    this.valueChangedEvent.callListeners();
  }
  sliderDragStarted() {}
  sliderDragEnded() {}
  getScaledValue() {
    return this.scaledValue;
  }
  getNormalisedValue() {
    const { start, end, skew } = this.properties;
    return Math.pow((this.scaledValue - start) / (end - start), skew);
  }
}

class MockToggleState {
  constructor(name) {
    this.name = name;
    this.identifier = "__juce__toggle" + name;
    this.value = false;
    this.properties = { name, parameterIndex: -1 };
    this.valueChangedEvent = new ListenerList();
    this.propertiesChangedEvent = new ListenerList();
  }
  getValue() { return this.value; }
  setValue(v) { this.value = !!v; this.valueChangedEvent.callListeners(); }
}

class MockComboBoxState {
  constructor(name) {
    this.name = name;
    this.identifier = "__juce__comboBox" + name;
    this.value = 0;
    this.properties = { name, parameterIndex: -1, choices: [] };
    this.valueChangedEvent = new ListenerList();
    this.propertiesChangedEvent = new ListenerList();
  }
  getChoiceIndex() { return this.value; }
  setChoiceIndex(i) { this.value = i; this.valueChangedEvent.callListeners(); }
}

const sliderStates = new Map();
const toggleStates = new Map();
const comboBoxStates = new Map();

export function getSliderState(name) {
  if (!sliderStates.has(name)) sliderStates.set(name, new MockSliderState(name));
  return sliderStates.get(name);
}

export function getToggleState(name) {
  if (!toggleStates.has(name)) toggleStates.set(name, new MockToggleState(name));
  return toggleStates.get(name);
}

export function getComboBoxState(name) {
  if (!comboBoxStates.has(name)) comboBoxStates.set(name, new MockComboBoxState(name));
  return comboBoxStates.get(name);
}

export function getNativeFunction(name) {
  return async (...args) => {
    console.warn("[gnarl] native function '" + name + "' called with no plugin backend", args);
    return undefined;
  };
}

export function getBackendResourceAddress(path) {
  return path;
}

export class ControlParameterIndexUpdater {
  constructor(annotation) { this.annotation = annotation; }
  handleMouseMove() {}
}
`;

/*
 * Types for JUCE's module. JUCE ships no .d.ts, so this file is ours and must
 * be kept in step with the framework version pinned in cmake/Dependencies.cmake.
 */
const FALLBACK_TYPES = `/* AUTO-GENERATED by scripts/sync-juce-frontend.mjs — do not edit.
 *
 * Hand-maintained types for JUCE's JavaScript frontend library, which ships
 * without any. Keep in step with the JUCE version pinned in
 * cmake/Dependencies.cmake.
 */

/** A JUCE ListenerList. addListener returns an opaque id for removeListener. */
export interface ListenerList {
  addListener(fn: (payload?: unknown) => void): number;
  removeListener(id: number): void;
  callListeners(payload?: unknown): void;
}

export interface SliderProperties {
  start: number;
  end: number;
  skew: number;
  name: string;
  label: string;
  numSteps: number;
  interval: number;
  parameterIndex: number;
}

export interface SliderState {
  readonly name: string;
  readonly identifier: string;
  readonly properties: SliderProperties;
  readonly valueChangedEvent: ListenerList;
  readonly propertiesChangedEvent: ListenerList;
  /** Value in [0, 1], matching AudioProcessorParameter::getValue(). */
  setNormalisedValue(newValue: number): void;
  /** Call before the first setNormalisedValue of a drag. */
  sliderDragStarted(): void;
  /** Call after the last setNormalisedValue of a drag. */
  sliderDragEnded(): void;
  getNormalisedValue(): number;
  getScaledValue(): number;
}

export interface ToggleProperties {
  name: string;
  parameterIndex: number;
}

export interface ToggleState {
  readonly name: string;
  readonly identifier: string;
  readonly properties: ToggleProperties;
  readonly valueChangedEvent: ListenerList;
  readonly propertiesChangedEvent: ListenerList;
  getValue(): boolean;
  setValue(value: boolean): void;
}

export interface ComboBoxProperties {
  name: string;
  parameterIndex: number;
  choices: string[];
}

export interface ComboBoxState {
  readonly name: string;
  readonly identifier: string;
  readonly properties: ComboBoxProperties;
  readonly valueChangedEvent: ListenerList;
  readonly propertiesChangedEvent: ListenerList;
  getChoiceIndex(): number;
  setChoiceIndex(index: number): void;
}

export function getSliderState(name: string): SliderState;
export function getToggleState(name: string): ToggleState;
export function getComboBoxState(name: string): ComboBoxState;

/** Calls a function registered with Options::withNativeFunction() in C++. */
export function getNativeFunction(
  name: string,
): (...args: unknown[]) => Promise<unknown>;

/** Rewrites a relative path to one the plugin's resource provider serves. */
export function getBackendResourceAddress(path: string): string;

/**
 * Reports the parameter under the mouse to the host, so a DAW can highlight
 * the matching automation lane. Wire it up in Phase 6.
 */
export class ControlParameterIndexUpdater {
  constructor(controlParameterIndexAnnotation: string);
  handleMouseMove(event: MouseEvent): void;
}
`;

const juceJsDir = findJuceJavascriptDir();

mkdirSync(target, { recursive: true });
writeFileSync(join(target, 'index.d.ts'), FALLBACK_TYPES);

if (juceJsDir) {
  const n = copyDirShallow(juceJsDir, target);
  console.log(`[gnarl] synced JUCE frontend (${n} files) from ${juceJsDir}`);
} else {
  writeFileSync(join(target, 'index.js'), FALLBACK);
  console.log('[gnarl] no JUCE checkout found — wrote dev-mode fallback to src/juce/');
  console.log('[gnarl] configure the CMake build once, then: npm run sync-juce');
}
